String _translatePattern(String source, Locale locale) {
  if (locale.languageCode == 'zh') return _toTraditional(source);

  final index = _languageIndex(locale);
  const cardModePrefixes = [
    '切換卡片模式，目前',
    'Switch card mode, current: ',
    'カード表示を切替：',
    '카드 보기 전환, 현재: ',
    'Chuyển chế độ thẻ, hiện tại: ',
    'Сменить режим карт, текущий: ',
    'Cambiar modo de tarjetas, actual: ',
    'Changer le mode des cartes, actuel : ',
    'Kartenmodus wechseln, aktuell: ',
    'Alternar modo dos cartões, atual: ',
    'Kart modunu değiştir, mevcut: ',
  ];
  if (source.startsWith('切换卡片模式，当前')) {
    return '${cardModePrefixes[index]}${textForLocale(source.substring('切换卡片模式，当前'.length), locale)}';
  }
  final ownedCards = RegExp(r'^已持有 (\d+) 张卡片$').firstMatch(source);
  if (ownedCards != null) {
    final count = ownedCards.group(1)!;
    final labels = [
      '已持有 $count 張卡片',
      '$count cards owned',
      '$count 枚のカードを所有',
      '보유 카드 $count장',
      'Đã có $count thẻ',
      'Карт в наличии: $count',
      '$count tarjetas',
      '$count cartes',
      '$count Karten',
      '$count cartões',
      '$count kart',
    ];
    return labels[index];
  }
  final favoriteCards = RegExp(r'^收藏 (\d+) 张$').firstMatch(source);
  if (favoriteCards != null) {
    final count = favoriteCards.group(1)!;
    final labels = [
      '收藏 $count 張',
      '$count favorites',
      'お気に入り $count 枚',
      '즐겨찾기 $count장',
      '$count yêu thích',
      'В избранном: $count',
      '$count favoritos',
      '$count favoris',
      '$count Favoriten',
      '$count favoritos',
      '$count favori',
    ];
    return labels[index];
  }
  final activitySummary = RegExp(
    r'^活跃天数 (\d+) 天 · 已采纳 (\d+) 条$',
  ).firstMatch(source);
  if (activitySummary != null) {
    final activeDays = activitySummary.group(1)!;
    final acceptedContributions = activitySummary.group(2)!;
    final labels = [
      '活躍天數 $activeDays 天 · 已採納 $acceptedContributions 條',
      '$activeDays active days · $acceptedContributions accepted',
      '$activeDays日間アクティブ · 採用 $acceptedContributions 件',
      '활동 $activeDays일 · 채택 $acceptedContributions건',
      'Hoạt động $activeDays ngày · Đã chấp nhận $acceptedContributions',
      '$activeDays активных дней · принято $acceptedContributions',
      '$activeDays días activo · $acceptedContributions aceptadas',
      '$activeDays jours actifs · $acceptedContributions acceptées',
      '$activeDays aktive Tage · $acceptedContributions akzeptiert',
      '$activeDays dias ativo · $acceptedContributions aceitas',
      '$activeDays etkin gün · $acceptedContributions kabul edildi',
    ];
    return labels[index];
  }
  final acceptedContributions = RegExp(r'^已采纳 (\d+) 条贡献$').firstMatch(source);
  if (acceptedContributions != null) {
    final count = acceptedContributions.group(1)!;
    final labels = [
      '已採納 $count 條貢獻',
      '$count accepted contributions',
      '採用された貢献 $count 件',
      '채택된 기여 $count건',
      '$count đóng góp được chấp nhận',
      'Принято вкладов: $count',
      '$count contribuciones aceptadas',
      '$count contributions acceptées',
      '$count angenommene Beiträge',
      '$count contribuições aceitas',
      '$count kabul edilen katkı',
    ];
    return labels[index];
  }
  const displayLanguagePrefixes = [
    '顯示語言已設為 ',
    'Display language set to ',
    '表示言語を設定しました：',
    '표시 언어: ',
    'Đã đặt ngôn ngữ: ',
    'Язык интерфейса: ',
    'Idioma configurado: ',
    'Langue définie : ',
    'Anzeigesprache: ',
    'Idioma definido: ',
    'Görüntüleme dili: ',
  ];
  if (source.startsWith('显示语言已设为 ')) {
    return '${displayLanguagePrefixes[index]}${source.substring('显示语言已设为 '.length)}';
  }
  const systemLanguagePrefixes = [
    '已跟隨系統語言：',
    'Following system language: ',
    'システム言語：',
    '시스템 언어: ',
    'Theo ngôn ngữ hệ thống: ',
    'Язык системы: ',
    'Idioma del sistema: ',
    'Langue du système : ',
    'Systemsprache: ',
    'Idioma do sistema: ',
    'Sistem dili: ',
  ];
  if (source.startsWith('已跟随系统语言：')) {
    return '${systemLanguagePrefixes[index]}${source.substring('已跟随系统语言：'.length)}';
  }
  // Exact catalog entries and the dynamic patterns above retain their native
  // translations. Until newer copy receives a reviewed translation, preserve
  // the original Chinese instead of showing English placeholder copy.
  if (locale.languageCode != 'en') {
    return source;
  }

  final resendCountdown = RegExp(r'^(\d+) 秒后可重新发送$').firstMatch(source);
  if (resendCountdown != null) {
    return 'Resend in ${resendCountdown.group(1)} seconds';
  }
  final linkedIdentity = RegExp(r'^(Apple|Google) 账号已绑定。$').firstMatch(source);
  if (linkedIdentity != null) {
    return '${linkedIdentity.group(1)} account linked.';
  }
  final publicComments = RegExp(r'^(\d+) 条公开评论$').firstMatch(source);
  if (publicComments != null) {
    final count = int.parse(publicComments.group(1)!);
    return '$count public ${count == 1 ? 'comment' : 'comments'}';
  }
  final publicCommentPreview = RegExp(r'^(\d+) 条公开$').firstMatch(source);
  if (publicCommentPreview != null) {
    return '${publicCommentPreview.group(1)} public';
  }
  final helpfulCount = RegExp(r'^有帮助 (\d+)$').firstMatch(source);
  if (helpfulCount != null) return 'Helpful ${helpfulCount.group(1)}';
  final minutesAgo = RegExp(r'^(\d+) 分钟前$').firstMatch(source);
  if (minutesAgo != null) return '${minutesAgo.group(1)}m ago';
  final hoursAgo = RegExp(r'^(\d+) 小时前$').firstMatch(source);
  if (hoursAgo != null) return '${hoursAgo.group(1)}h ago';
  final daysAgo = RegExp(r'^(\d+) 天前$').firstMatch(source);
  if (daysAgo != null) return '${daysAgo.group(1)}d ago';

  final exactFallback = _englishFallbackPhrases[source];
  if (exactFallback != null) return exactFallback;

  var value = source;
  final fallbacks = _englishFallbackPhrases.entries.toList(growable: false)
    ..sort((a, b) => b.key.length.compareTo(a.key.length));
  for (final entry in fallbacks) {
    value = value.replaceAll(entry.key, entry.value);
  }
  final entries = _catalog.entries.toList(growable: false)
    ..sort((a, b) => b.key.length.compareTo(a.key.length));
  for (final entry in entries) {
    if (value.contains(entry.key)) {
      value = value.replaceAll(entry.key, entry.value[index]);
    }
  }
  // Do not present a partly translated sentence as English. Remote content
  // and newly curated catalog data can arrive before their exact translation
  // is added above; keep the complete original Chinese sentence until a
  // reviewed translation is available.
  if (_containsChinese(value)) {
    return source;
  }
  return value;
}

