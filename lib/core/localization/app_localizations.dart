/// App-owned localization for visible product copy.
///
/// Chinese source copy is used as the stable lookup key so existing screens can
/// be migrated without coupling product text to widget structure. New copy
/// should be added to [_catalog] before it is shipped.
class AppLocalizations {
  const AppLocalizations(this.locale);

  final Locale locale;

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations) ??
      const AppLocalizations(Locale('zh', 'CN'));

  static const delegate = _AppLocalizationsDelegate();

  String text(String source) {
    if (source.isEmpty ||
        locale.languageCode == 'zh' && locale.countryCode != 'HK') {
      return source;
    }

    final translated = _catalog[source]?[_languageIndex(locale)];
    if (translated != null && translated.isNotEmpty) return translated;

    return _translatePattern(source, locale);
  }
}

extension AppLocalizationContext on BuildContext {
  String tr(String source) => AppLocalizations.of(this).text(source);
}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => const {
    'zh',
    'en',
    'ja',
    'ko',
    'vi',
    'ru',
    'es',
    'fr',
    'de',
    'pt',
    'tr',
  }.contains(locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) =>
      SynchronousFuture(AppLocalizations(locale));

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

// zh-HK, en, ja, ko, vi, ru, es, fr, de, pt-BR, tr
int _languageIndex(Locale locale) {
  if (locale.languageCode == 'zh') return 0;
  return const {
        'en': 1,
        'ja': 2,
        'ko': 3,
        'vi': 4,
        'ru': 5,
        'es': 6,
        'fr': 7,
        'de': 8,
        'pt': 9,
        'tr': 10,
      }[locale.languageCode] ??
      1;
}

